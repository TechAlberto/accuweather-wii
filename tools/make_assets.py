#!/usr/bin/env python3
"""Generate the embedded image and certificate assets.

Two jobs:

  logo   Take the AccuWeather wordmark out of the Android APK and turn it into
         two GX_TF_IA8 masks -- the white wordmark and the orange sun -- so the
         header can draw the real brand art with the same four-vertex path the
         font atlas uses.  Run with --apk to regenerate:

             python tools/make_assets.py --apk <path to accuweather apk>

  certs  Turn certs/cacert.pem (the Mozilla bundle from curl.se) into a C string
         header, source/ca_bundle.h.

Everything is written already tiled for GX, so the runtime just copies it into
an aligned buffer.
"""
import argparse
import io
import os
import sys

try:
    from PIL import Image
except ImportError:
    Image = None

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The wordmark lockup shipped in the APK at res/drawable/widget_branding_dark_med.png
# is 400x60.  The header draws it at 190x28, so rasterise a little above that
# and let the GPU's bilinear filter do the rest.
LOGO_SRC = "res/drawable/widget_branding_dark_med.png"
LOGO_W, LOGO_H = 240, 36

ACCENT = (240, 88, 35)


def tile_ia8(alpha, w, h):
    """Pack coverage into GX_TF_IA8: 4x4 tiles, 32 bytes each, (alpha, 255)."""
    out = bytearray(w * h * 2)
    for by in range(0, h, 4):
        for bx in range(0, w, 4):
            base = ((by >> 2) * (w >> 2) + (bx >> 2)) * 32
            for y in range(4):
                for x in range(4):
                    a = alpha[by + y][bx + x] if by + y < h and bx + x < w else 0
                    off = base + (y << 3) + (x << 1)
                    out[off] = a
                    out[off + 1] = 255
    return bytes(out)


def make_logo(apk):
    import zipfile

    data = zipfile.ZipFile(apk).read(LOGO_SRC)
    im = Image.open(io.BytesIO(data)).convert("RGBA").resize(
        (LOGO_W, LOGO_H), Image.LANCZOS)
    px = im.load()

    white = [[0] * LOGO_W for _ in range(LOGO_H)]
    accent = [[0] * LOGO_W for _ in range(LOGO_H)]
    for y in range(LOGO_H):
        for x in range(LOGO_W):
            r, g, b, a = px[x, y]
            if not a:
                continue
            # The sun is the only saturated part of the lockup: its antialiased
            # edge pixels are still far redder than they are blue, while the
            # wordmark and its antialiasing stay neutral.
            if r - b > 30:
                accent[y][x] = a
            else:
                white[y][x] = a

    # One texture, two masks stacked: white text on top, orange sun below.
    # ui.c draws the two halves with separate vertex colours.
    stacked = tile_ia8(white, LOGO_W, LOGO_H) + tile_ia8(accent, LOGO_W, LOGO_H)
    with open(os.path.join(ROOT, "data", "logo.bin"), "wb") as f:
        f.write(stacked)

    with open(os.path.join(ROOT, "source", "logo_assets.h"), "w", newline="\n") as f:
        f.write("/* Generated by tools/make_assets.py -- do not edit. */\n")
        f.write("#ifndef LOGO_ASSETS_H\n#define LOGO_ASSETS_H\n\n")
        f.write("/* data/logo.bin: %dx%d, white mask above orange mask. */\n"
                % (LOGO_W, LOGO_H * 2))
        f.write("#define LOGO_W %d\n#define LOGO_H %d\n" % (LOGO_W, LOGO_H))
        f.write("#define LOGO_ACCENT_R %d\n#define LOGO_ACCENT_G %d\n"
                "#define LOGO_ACCENT_B %d\n" % ACCENT)
        f.write("\nextern const unsigned char logo_bin[];\n\n#endif\n")
    print("logo: %dx%d stacked -> data/logo.bin" % (LOGO_W, LOGO_H))


def make_ca_bundle():
    src = os.path.join(ROOT, "certs", "cacert.pem")
    with open(src, "r", encoding="utf-8") as f:
        pem = f.read()

    out = os.path.join(ROOT, "source", "ca_bundle.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/make_assets.py from data/cacert.pem.\n"
                " * Mozilla CA bundle, https://curl.se/ca/cacert.pem -- do not edit. */\n")
        f.write("#ifndef CA_BUNDLE_H\n#define CA_BUNDLE_H\n\n")
        f.write("static const char CA_BUNDLE_PEM[] =\n")
        for line in pem.splitlines():
            # Keep the header plain ASCII: the bundle's comments contain a few
            # accented names, which the PEM parser skips anyway.
            line = line.encode("ascii", "ignore").decode("ascii")
            f.write('    "%s\\n"\n' % line)
        f.write("    ;\n\n#endif\n")
    print("certs: %d bytes -> source/ca_bundle.h" % len(pem))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apk", help="path to the AccuWeather APK (regenerates the logo)")
    args = ap.parse_args()

    if args.apk:
        if Image is None:
            sys.exit("Pillow is required to regenerate the logo")
        make_logo(args.apk)
    make_ca_bundle()


if __name__ == "__main__":
    main()
