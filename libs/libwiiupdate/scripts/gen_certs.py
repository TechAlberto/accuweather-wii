#!/usr/bin/env python3
"""Regenerate source/wiiupdate_certs.h from the Mozilla CA bundle.

    curl -sSLf -o cacert.pem https://curl.se/ca/cacert.pem
    python3 scripts/gen_certs.py cacert.pem > source/wiiupdate_certs.h

Only the roots that api.github.com chains to (now or plausibly next) are kept,
so the bundle stays small enough to parse quickly on the Wii.
"""
import sys

WANTED = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "DigiCert Global Root G2",
    "ISRG Root X1",
    "ISRG Root X2",
]

text = open(sys.argv[1], encoding="utf-8").read().splitlines()
certs = {}
for i, line in enumerate(text):
    if line.strip() in WANTED and i + 2 < len(text) and text[i + 1].startswith("="):
        j = i + 2
        while not text[j].startswith("-----BEGIN"):
            j += 1
        k = j
        while not text[k].startswith("-----END"):
            k += 1
        certs[line.strip()] = text[j:k + 1]

missing = [n for n in WANTED if n not in certs]
if missing:
    sys.exit("missing roots: " + ", ".join(missing))

print("/* Root certificates for api.github.com, from the Mozilla CA bundle (curl.se).")
print(" * Generated by scripts/gen_certs.py; do not edit. */")
print("#pragma once\n")
print("static const char WIIUPDATE_CA_PEM[] =")
for name in WANTED:
    print(f"    /* {name} */")
    for l in certs[name]:
        print(f'    "{l}\\n"')
print("    ;")
